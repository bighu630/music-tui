// Package coverrender 提供封面图像的终端渲染：单元图形协议序列（kitty/sixel）与
// 半块自绘回退，以及共享的等比例缩放几何。
//
// 设计约束（来源于 music-tui 实际终端验证与 bubbletea 渲染管线探针）：
//   - bubbletea 的默认渲染器按行对 view 字符串做 diff 并逐行直通写入（未变行跳过、
//     Truncate 宽度感知：APC/DCS 计零宽）。因此 kitty 的图形序列**可以安全地内联在
//     布局文本流里**（APC 零宽、网格驻留、不被布局差分破坏），但**前提是终端真的支持
//     该协议**——不支持时会把 APC 载荷当作字面文本打印（页面视觉崩坏）。
//   - sixel 的 DCS 内联会让终端光标按图像像素高下跳（打乱流式布局），故本包只提供
//     全帧画布 DCS 载荷，由集成层以**外带绝对定位**方式写出（在屏幕坐标上直接画图，
//     像素驻留、覆盖文本网格中的占位区）。
//   - 探测必须保守：宁可回退半块，也不向不支持的终端发送协议字节。环境变量
//     MUSIC_TUI_COVER=kitty|sixel|halfblocks 可显式强制。
package coverrender

